"""ACQ-R04 §6 — every table of the report, generated from the run's JSON/CSV files (no typed numbers).

Writes reports_post_grl_review/ACQ-R04/tables/<name>.md and tables.json (the numbers the bottom line cites).
Usage: python -m src.acq_r04.tables [--manifest pretrain_manifest_v1.parquet]
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

from src.acq_r04 import common as R

T = R.REPORT_DIR / "tables"


def to_md(df: pd.DataFrame) -> str:
    def cell(v):
        if isinstance(v, float):
            return "" if np.isnan(v) else (f"{v:,.0f}" if abs(v) >= 1000 else f"{v:.4g}")
        if isinstance(v, (int, np.integer)):
            return f"{int(v):,}"
        return str(v).replace("|", "\\|")
    cols = [str(c) for c in df.columns]
    lines = ["| " + " | ".join(cols) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    lines += ["| " + " | ".join(cell(v) for v in row) + " |" for row in df.itertuples(index=False)]
    return "\n".join(lines)


def md(df: pd.DataFrame, name: str, note: str = "") -> str:
    T.mkdir(parents=True, exist_ok=True)
    txt = (f"<!-- generated by src/acq_r04/tables.py from {note} -->\n" if note else "") + to_md(df)
    (T / f"{name}.md").write_text(txt + "\n")
    return txt


def load(name):
    p = R.REPORT_DIR / name
    return json.loads(p.read_text()) if p.exists() else None


def main(argv=None):
    ap = argparse.ArgumentParser(); ap.add_argument("--manifest", default="pretrain_manifest_v1.parquet")
    a = ap.parse_args(argv)
    out = {}
    # ---- §1 exclusion
    ex = load("exclusion_v1.json")
    c = ex["counts"]
    rules = ["1_shared_cruise", "2_spatial", "3_composite", "4_non_ship"]
    md(pd.DataFrame({"rule": rules, "excluded (rule holds)": [c["by_rule_any"][r] for r in rules],
                     "excluded (first rule in order 1-4)": [c["by_rule_first_in_order_1_to_4"][r] for r in rules],
                     "excluded (only this rule)": [c["by_rule_only"][r] for r in rules]}), "exclusion_by_rule", "exclusion_v1.json:counts")
    cmp_ = ex["acq_r01_comparison"]
    ex_rows = [{"cruise": k, "why now excluded": ", ".join(v["rules"]) + (": " + "; ".join(sorted(set(v["spatial_hits"])))[:120] if v["spatial_hits"] else "")
                + (" | ids: " + "; ".join(s.split(":", 1)[0] for s in v["shared_ids"])[:80] if v["shared_ids"] else "")}
               for k, v in sorted(cmp_["in_acq_r01_not_in_pool"].items())]
    in_rows = [{"cruise": k, "ACQ-R01 excluded it by": ("id (" + (v["r01_id_source"] or "") + ")" if v["r01_excl_by_id"] else "") +
                (" + " if v["r01_excl_by_id"] and v["r01_excl_by_zone"] else "") + ("10 km zone of a §3 candidate HR footprint (EPSG:6933)" if v["r01_excl_by_zone"] else "")}
               for k, v in sorted(cmp_["in_pool_not_in_acq_r01"].items())]
    md(pd.DataFrame(ex_rows), "r01_diff_newly_excluded", "exclusion_v1.json:acq_r01_comparison.in_acq_r01_not_in_pool")
    md(pd.DataFrame(in_rows), "r01_diff_newly_included", "exclusion_v1.json:acq_r01_comparison.in_pool_not_in_acq_r01")
    inc_reason = pd.Series([r["ACQ-R01 excluded it by"] for r in in_rows]).value_counts()
    md(inc_reason.rename_axis("ACQ-R01 exclusion reason").reset_index(name="cruises now in pool"), "r01_diff_included_reasons", "exclusion_v1.json")
    out["exclusion"] = {**c, "acq_r01_records": cmp_["acq_r01_rerun_remaining_records"], "acq_r01_unique": cmp_["acq_r01_rerun_remaining_unique_ids"],
                        "newly_excluded": len(ex_rows), "newly_included": len(in_rows)}
    pool = pd.read_csv(R.REPORT_DIR / "pool_v1.csv")
    md(pool.crawl_status.value_counts().rename_axis("crawl_status").reset_index(name="pool cruises"), "pool_status", "pool_v1.csv:crawl_status")
    fam = pool.groupby("family").agg(pool=("survey_id", "count"), readable=("readable", "sum"),
                                     readable_TB=("advertised_bytes", lambda s: round(s[pool.loc[s.index, "readable"]].sum() / 1e12, 3))).reset_index()
    md(fam, "pool_by_family", "pool_v1.csv")
    out["pool"] = {"cruises": int(len(pool)), "readable": int(pool.readable.sum()), "readable_frac": round(float(pool.readable.mean()), 4),
                   "readable_TB": round(float(pool.loc[pool.readable, "advertised_bytes"].sum()) / 1e12, 3)}
    # ---- §2 selection
    sj = load("selection_v1.json"); sel = pd.read_csv(R.REPORT_DIR / "selection_v1.csv")
    st = sel.groupby("stratum").agg(cruises=("cruise", "count"), advertised_GB=("advertised_bytes", lambda s: round(s.sum() / 1e9, 1))).reset_index()
    st["pool (readable)"] = st.stratum.map(sj["stratum_sizes"])
    md(st, "selection_by_stratum", "selection_v1.csv, selection_v1.json:stratum_sizes")
    md(pd.DataFrame(sj["replacements"]).assign(removed_GB=lambda d: (d.removed_bytes / 1e9).round(1), added_GB=lambda d: (d.added_bytes / 1e9).round(1),
                                               total_after_TB=lambda d: (d.total_after_bytes / 1e12).round(4))
       [["round", "stratum", "over_representation", "removed", "removed_GB", "added", "added_GB", "total_after_TB"]], "selection_replacements", "selection_v1.json:replacements")
    out["selection"] = {k: sj[k] for k in ("n_selected", "total_tb_final", "n_replacements", "total_bytes_initial", "files_planned", "selected_per_family", "selected_per_basin")}
    # ---- §3.1 pilot
    pj = load("pilot_v1.json")
    if pj:
        pdf = pd.read_csv(R.REPORT_DIR / "pilot_v1.csv")
        pdf["raw_GB"] = (pdf.raw_bytes / 1e9).round(2); pdf["output_MB"] = (pdf.output_bytes / 1e6).round(1)
        md(pdf[["cruise", "family", "files", "raw_GB", "fetch_s", "decompress_s", "coverage_s", "grid_s", "products_s", "process_wall_s",
                "blocks_total", "blocks_kept", "output_MB", "failures"]], "pilot", "pilot_v1.csv")
        md(pd.DataFrame([{"quantity": k, "extrapolated": v, "limit": {"raw_download_TB": 3.0, "full_run_wall_h": 96.0, "oak_output_GB": 600.0}.get(k, "")}
                         for k, v in pj["extrapolation"].items()]), "pilot_extrapolation", "pilot_v1.json:extrapolation")
        out["pilot"] = {"extrapolation": pj["extrapolation"], "any_hold": pj["any_hold"], "hold": pj["hold"], "concurrency": pj["concurrency_assumed"],
                        "fetch_rate_MBps": pj["fetch_rate_MBps"]}
    # ---- §3.5 corpus
    mp = R.REPORT_DIR / a.manifest
    if mp.exists():
        man = pd.read_parquet(mp)
        man["depth_band"] = pd.cut(man.median_depth_m, [300, 1500, 4000, 6500], right=False, labels=["300-1,500", "1,500-4,000", "4,000-6,500"])
        man["cell_band"] = pd.cut(man.cell_m, [0, 20, 40, 80, 120, np.inf], right=False, labels=["<20", "20-40", "40-80", "80-120", ">=120"])
        md(man.groupby("instrument_family").agg(cruises=("cruise", "nunique"), blocks=("block", "count")).reset_index(), "corpus_by_family", a.manifest)
        md(man.groupby("basin").agg(cruises=("cruise", "nunique"), blocks=("block", "count")).reset_index(), "corpus_by_basin", a.manifest)
        md(man.groupby("depth_band", observed=False).agg(blocks=("block", "count")).reset_index(), "corpus_by_depth", a.manifest)
        ct = pd.crosstab(man.instrument_family, man.cell_band, margins=True, margins_name="all").reset_index()
        md(ct, "cell_size_coverage", a.manifest)
        # vertical_offset flag: median offset (ship_median_regrid - grid.tif, m) against block depth (steering ruling 2026-10-03)
        vo = man[man.products_flags.fillna("").str.contains("vertical_offset")].copy()
        if len(man):
            man["vo"] = man.products_flags.fillna("").str.contains("vertical_offset")
            dbins = pd.cut(man.median_depth_m, [300, 1000, 2000, 3000, 4000, 5000, 6500], right=False)
            g = man.groupby(dbins, observed=False)
            tab = pd.DataFrame({"blocks": g.size(), "flagged_vertical_offset": g.vo.sum(),
                                "median_offset_all_m (median)": g.qa_median_offset_m.median(),
                                "median_offset_flagged_m (median)": man[man.vo].groupby(dbins[man.vo], observed=False).qa_median_offset_m.median(),
                                "median_offset_flagged_m (min)": man[man.vo].groupby(dbins[man.vo], observed=False).qa_median_offset_m.min(),
                                "median_offset_flagged_m (max)": man[man.vo].groupby(dbins[man.vo], observed=False).qa_median_offset_m.max(),
                                "abs_offset/depth_flagged (median)": (man[man.vo].qa_median_offset_m.abs() / man[man.vo].median_depth_m).groupby(dbins[man.vo], observed=False).median()}).reset_index()
            tab = tab.rename(columns={"median_depth_m": "depth band (m)"}); tab["depth band (m)"] = tab["depth band (m)"].astype(str)
            md(tab, "vertical_offset_vs_depth", a.manifest + " (qa_median_offset_m from each block's products.json)")
            import matplotlib; matplotlib.use("Agg"); import matplotlib.pyplot as plt
            fig, ax = plt.subplots(figsize=(7, 4.5))
            ax.scatter(man.loc[~man.vo, "median_depth_m"], man.loc[~man.vo, "qa_median_offset_m"], s=6, c="#9aa5b1", label="not flagged")
            ax.scatter(vo.median_depth_m, vo.qa_median_offset_m, s=8, c="#c2410c", label="vertical_offset flag")
            ax.axhline(0.5, lw=0.8, ls="--", c="k"); ax.axhline(-0.5, lw=0.8, ls="--", c="k")
            ax.set_xlabel("block median depth (m)"); ax.set_ylabel("QA median offset, ship median − grid.tif (m)")
            ax.set_title("Contract v2.1 QA: median offset vs depth (dashed: ±0.5 m threshold)"); ax.legend(frameon=False)
            fig.tight_layout(); fig.savefig(T / "vertical_offset_vs_depth.png", dpi=120); plt.close(fig)
            out["vertical_offset"] = {"flagged": int(man.vo.sum()), "blocks": int(len(man)),
                                      "spearman_abs_offset_vs_depth_flagged": float(vo.qa_median_offset_m.abs().corr(vo.median_depth_m, method="spearman")) if len(vo) > 2 else None}
        fl = man.products_flags.fillna("").str.split(";").explode()
        md(fl[fl != ""].value_counts().rename_axis("flag").reset_index(name="blocks"), "product_flags", a.manifest)
        out["corpus"] = {"blocks": int(len(man)), "cruises": int(man.cruise.nunique()), "cell_min": float(man.cell_m.min()), "cell_max": float(man.cell_m.max()),
                         "cell_median": float(man.cell_m.median()), "below_10m": int((man.cell_m < 10).sum()), "above_87m": int((man.cell_m > 87).sum()),
                         "within_10_87": int(((man.cell_m >= 10) & (man.cell_m <= 87)).sum()),
                         "usable": int(man.products_usable.sum()), "flagged": int((man.products_flags.fillna("") != "").sum()),
                         "product_errors": int(man.products_error.notna().sum())}
    led = R.REPORT_DIR / "failure_ledger_v1.csv"
    if led.exists():
        L = pd.read_csv(led)
        md(L.groupby(["level", "stage"]).size().rename("entries").reset_index(), "failure_ledger_totals", "failure_ledger_v1.csv")
        out["ledger"] = L.groupby("stage").size().to_dict()
    ec = load("exclusion_check_v1.json")
    if ec:
        out["check_4_1"] = ec
    rc = R.REPORT_DIR / "repro_check_v1.csv"
    if rc.exists():
        r = pd.read_csv(rc)
        md(r.pivot_table(index=["cruise", "block", "family"], columns="raster", values="max_abs_diff", aggfunc="first").reset_index(), "repro_max_abs_diff", "repro_check_v1.csv")
        md(r.pivot_table(index=["cruise", "block"], columns="raster", values="nan_mismatch", aggfunc="first").reset_index(), "repro_nan_mismatch", "repro_check_v1.csv")
        out["repro"] = {"blocks": int(r.block.nunique()), "max_abs_diff_overall": float(r.max_abs_diff.max()), "nan_mismatch_total": int(r.nan_mismatch.sum()),
                        "families": int(r.family.nunique())}
    pv = load("persist_verify.json")
    if pv:
        out["persist"] = {k: pv[k] for k in ("files", "gb", "verified_ok", "cruise_tars", "blocks", "tar_members", "sha256sums_sha256")} | \
            {"not_ok": len(pv["not_ok"]), "vsitar_sha_ok": pv["vsitar_sample"]["sha_ok"], "vsitar_cruises": pv["vsitar_sample"]["cruises"]}
    R.write_json(R.REPORT_DIR / "tables.json", out)
    print(json.dumps(out, indent=1, default=str))
    return 0


if __name__ == "__main__":
    sys.exit(main())
