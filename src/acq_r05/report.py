"""ACQ-R05 §8 — assemble REPORT_ACQ-R05_<date>.md from REPORT_ACQ-R05_template.md (ACQ-R04 report.py mechanism).

{{table:<name>}}            -> tables/<name>.md inserted verbatim (generated by tables.py)
{{json:<file>:<key.path>}}  -> the value at that key of that JSON (report dir), so no number in the prose is typed.
Fails loudly on any missing table or key.  Usage: python -m src.acq_r05.report [--date 2026-10-09]
"""
from __future__ import annotations

import argparse
import json
import re
import sys

from src.acq_r05 import common as R


def lookup(fname, keypath):
    obj = json.loads((R.REPORT_DIR / fname).read_text())
    for k in keypath.split("."):
        obj = obj[int(k)] if isinstance(obj, list) else obj[k]
    if isinstance(obj, bool):
        return "yes" if obj else "no"
    if isinstance(obj, float):
        return f"{obj:,.4g}" if abs(obj) < 1000 else f"{obj:,.1f}"
    if isinstance(obj, int):
        return f"{obj:,}"
    if isinstance(obj, list):
        return ", ".join(f"{x:.3g}" if isinstance(x, float) else str(x) for x in obj) if obj else "none"
    return str(obj)


def main(argv=None):
    ap = argparse.ArgumentParser(); ap.add_argument("--date", default="2026-10-09")
    a = ap.parse_args(argv)
    t = (R.REPORT_DIR / "REPORT_ACQ-R05_template.md").read_text()
    t = re.sub(r"\{\{table:([\w\-]+)\}\}", lambda m: (R.REPORT_DIR / "tables" / f"{m.group(1)}.md").read_text().strip(), t)
    t = re.sub(r"\{\{json:([\w\-.]+?\.json):([\w.\-]+)\}\}", lambda m: lookup(m.group(1), m.group(2)), t)
    left = re.findall(r"\{\{[^}]+\}\}", t)
    if left:
        raise SystemExit(f"unresolved placeholders: {left}")
    out = R.REPORT_DIR / f"REPORT_ACQ-R05_{a.date}.md"
    out.write_text(t)
    print(out, len(t.splitlines()), "lines")
    return 0


if __name__ == "__main__":
    sys.exit(main())
