    srcs = {Path(p).stem.replace("_sources", ""): json.loads(Path(p).read_text()) for p in glob.glob(str(R.REPORT_DIR / "sources" / "*_sources.json"))}
    lat = json.loads((R.REPORT_DIR / "lattice_recovery.json").read_text())["pairs"]
    guard = json.loads((R.REPORT_DIR / "guard_selftest.json").read_text())
    numbers = {"generated": R.utc_now(), "n_pairs_in_scope": len(R.PAIRS_IN_SCOPE), "n_provider": len(R.PROVIDER_PAIRS), "n_ncei": len(R.NCEI_PAIRS),
               "guard": {"readers_blocked": guard["reader_checks"]["n_blocked"], "readers_n": guard["reader_checks"]["n"], "builder_refused": guard["builder_refusals"]["n_refused"],
                         "builder_n": guard["builder_refusals"]["n"], "all_passed": guard["all_passed"]}}
    # 1 scope
    rows = [{"unit": R.UNIT_OF[p], "pair_id": p, "kind": "provider_grid" if R.is_provider(p) else lat[p]["source_lattice"]["kind"], "lr_cruise": R.lr_cruise(p),
             "built": p in builds} for p in R.PAIRS_IN_SCOPE]
    scope = pd.DataFrame(rows); md(scope, "scope", "lattice_recovery.json + builds/")
    numbers["n_built"] = int(scope.built.sum()); numbers["n_not_built"] = int((~scope.built).sum())
    numbers["not_built"] = scope[~scope.built].pair_id.tolist()
    # 2 lattice recovery
    rows = []
    for p in R.NCEI_PAIRS:
        s = lat[p]["source_lattice"]; v = lat[p]["verification"]; c = lat[p]["context"]; g = lat[p]["context_region"]
        rows.append({"pair_id": p, "stage-C lattice": s["kind"], "cell_rule": s.get("cell_rule", "grd header"), "cell_m": f3(s.get("cell_m")), "source nx x ny": f"{s['nx']} x {s['ny']}",
                     "verified (GDAL default warp == lr.tif lattice)": "yes" if v["match"] else "NO", "pixel size rel. diff": f"{v['pixel_size_rel_diff']:.1e}",
                     "lr offset in warped (px)": f"{v['lr_offset_in_warped_px'][0]:.6f}, {v['lr_offset_in_warped_px'][1]:.6f}",
                     "context nx x ny": f"{c['width']} x {c['height']}", "context mbgrid nodes": f"{g['nx']} x {g['ny']}"})
    md(pd.DataFrame(rows), "lattice_recovery", "lattice_recovery.json")
    numbers["lattice_verified"] = int(sum(lat[p]["verification"]["match"] for p in R.NCEI_PAIRS))
    # 3 sources
    rows = []
    for c, s in sorted(srcs.items()):
        pl = s.get("plan", {}); fe = s.get("fetch", {}); cv = s.get("coverage", {})
