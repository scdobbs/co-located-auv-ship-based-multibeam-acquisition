"""ACQ-R06 §E — assemble REPORT_ACQ-R06_<date>.md from REPORT_ACQ-R06_template.md (the ACQ-R04/R05 report.py mechanism).

{{table:<name>}}            -> tables/<name>.md inserted verbatim (generated by tables.py)
{{json:<file>:<key.path>}}  -> the value at that key of that JSON (report dir), so no number in the prose is typed.
Fails loudly on any missing table or key.  Usage: python -m src.phase4.report [--date 2026-10-10]
"""
from __future__ import annotations

import argparse
import json
import re
import sys

from src.phase4 import common as P


def lookup(fname, keypath):
    obj = json.loads((P.REPORT_DIR / fname).read_text())
    rest = keypath
    while rest:
        if isinstance(obj, dict) and rest in obj:            # keys may contain dots or slashes (file names): longest match first
            obj = obj[rest]; break
        k, _, rest = rest.partition(".")
        obj = obj[int(k)] if isinstance(obj, list) else obj[k]
    if isinstance(obj, bool):
        return "yes" if obj else "no"
    if isinstance(obj, float):
        return f"{obj:,.4g}" if abs(obj) < 1000 else f"{obj:,.1f}"
    if isinstance(obj, int):
        return f"{obj:,}"
    if isinstance(obj, list):
        return ", ".join(f"{x:.3g}" if isinstance(x, float) else str(x) for x in obj) if obj else "none"
    if obj is None:
        return "none"
    return str(obj)


def main(argv=None):
    ap = argparse.ArgumentParser(); ap.add_argument("--date", default="2026-10-10")
    a = ap.parse_args(argv)
    t = (P.REPORT_DIR / "REPORT_ACQ-R06_template.md").read_text()
    t = re.sub(r"\{\{table:([\w\-]+)\}\}", lambda m: (P.REPORT_DIR / "tables" / f"{m.group(1)}.md").read_text().strip(), t)
    t = re.sub(r"\{\{json:([\w\-.]+?\.json):([\w.\-/ ]+?)\}\}", lambda m: lookup(m.group(1), m.group(2)), t)
    left = re.findall(r"\{\{[^}]+\}\}", t)
    if left:
        raise SystemExit(f"unresolved placeholders: {left}")
    out = P.REPORT_DIR / f"REPORT_ACQ-R06_{a.date}.md"
    out.write_text(t)
    print(out, len(t.splitlines()), "lines")
    return 0


if __name__ == "__main__":
    sys.exit(main())
