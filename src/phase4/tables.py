"""ACQ-R06 §E — every table of the report, generated from the run's JSON files (no typed numbers).

Writes reports_post_grl_review/ACQ-R06/tables/<name>.md and tables.json (the numbers the bottom line cites).
Usage: python -m src.phase4.tables --run-tag full
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

import numpy as np
import pandas as pd

from src.acq_r04.tables import to_md
from src.phase4 import common as P

T = P.REPORT_DIR / "tables"


def md(df: pd.DataFrame, name: str, note: str = "") -> str:
    T.mkdir(parents=True, exist_ok=True)
    df = df.copy()
    for c in df.columns:
        if df[c].dtype == bool:
            df[c] = df[c].map({True: "yes", False: "no"})
        else:
            df[c] = df[c].map(lambda v: "yes" if v is True else ("no" if v is False else v))
    txt = (f"<!-- generated by src/phase4/tables.py from {note} -->\n" if note else "") + to_md(df)
    (T / f"{name}.md").write_text(txt + "\n")
    return txt


def yn(v):
    return "yes" if v else "no"


def mode_branches() -> pd.DataFrame:
    src = (P.REPO / "src/phase4/sealed_step1.py").read_text().splitlines()
    rows = []
    for i, line in enumerate(src, 1):
        if re.search(r"a\.mode\s*==|MODES\s*=|MODES\[|cfg\[\"mode\"\]|cfg\['mode'\]|\"rehearsal\":|\"phase4\":", line):
            rows.append({"line": i, "code": line.strip()[:150]})
    return pd.DataFrame(rows)


def main(argv=None):
    ap = argparse.ArgumentParser(); ap.add_argument("--run-tag", default="full")
    a = ap.parse_args(argv)
    cmp = json.loads((P.REHEARSAL_DIR / f"compare_{a.run_tag}.json").read_text())
    run = json.loads((P.REHEARSAL_DIR / f"step1_run_rehearsal_{a.run_tag}.json").read_text())
    guard = json.loads((P.REPORT_DIR / "guard_selftest.json").read_text())
    ref = json.loads((P.REPORT_DIR / "refusal_tests.json").read_text())
    sr = json.loads((P.REPORT_DIR / "sealed_records.json").read_text())
    c1 = json.loads((P.REPORT_DIR / "c1_check.json").read_text())
    fz_p = P.REPORT_DIR / "freeze_record.json"; fz_c = P.REPORT_DIR / "freeze_record_candidate.json"
    fz = json.loads(fz_p.read_text()) if fz_p.exists() else (json.loads(fz_c.read_text()) if fz_c.exists() else None)
    numbers = {"generated": P.utc_now(), "code_commit": P.git_commit(), "run_tag": a.run_tag, "run_job": None,
               "guard": {"readers_blocked": guard["reader_checks"]["n_blocked"], "readers_n": guard["reader_checks"]["n"], "all_passed": guard["all_passed"],
                         "extension": guard.get("guard_extension"), "guard_sha256": guard.get("guard_sha256")},
               "refusal": {"n_tests": ref["n_tests"], "n_passed": ref["n_passed"], "all_passed": ref["all_passed"]},
               "fixed_inputs": run["fixed_input_sha256"], "cpu_models": cmp["cpu_models"], "wall_s_total": run["wall_s"], "host": run["host"]}
    jobs = P.REPORT_DIR / "rehearsal_jobs.txt"
    if jobs.exists():
        numbers["run_job"] = [l.split()[0] for l in jobs.read_text().splitlines() if l.split() and l.split()[1] == a.run_tag][-1]
    # guard
    md(pd.DataFrame([{"check": "readers x sealed targets blocked", "value": f"{guard['reader_checks']['n_blocked']} / {guard['reader_checks']['n']}"},
                     {"check": "controls", "value": "; ".join(f"{k}: {v}" for k, v in guard["controls"].items())},
                     {"check": "phase4 allowance installed", "value": str(guard["phase4_allowance_installed"]) or "none"},
                     {"check": "extension", "value": guard.get("guard_extension")},
                     {"check": "src/acq_r01/common.py sha256", "value": guard.get("guard_sha256")}]), "guard", "guard_selftest.json")
    # refusal tests
    md(pd.DataFrame([{"test": t["test"], "passed": t["passed"], "raised": t["raised"], "message": t["message"][:160]} for t in ref["tests"]]), "refusal_tests", "refusal_tests.json")
    # mode branches
    md(mode_branches(), "mode_branches", "src/phase4/sealed_step1.py (grep of every line that consults the mode)")
    # spacings + k
    rows = []
    for r in cmp["pairs"]:
        s0, s1, k = r["spacings"][0], r["spacings"][1], r["k"]; c = r["c2a"]
        rows.append({"pair_id": r["pair_id"], "unit": r["unit"], "hr computed": s0["computed"], "hr manifest": s0["manifest"], "hr identical": s0["identical"],
                     "lr computed": s1["computed"], "lr manifest": s1["manifest"], "lr identical": s1["identical"], "lr diff (m)": s1["diff"],
                     "k computed": k["computed"], "k manifest": k["manifest"], "k identical": k["identical"], "status computed": k["status_computed"], "status manifest": k["status_manifest"],
                     "sonar (source)": f"{c['sonar']} ({'grid record' if c['sonar_source'].startswith('ACQ-R02 grid record') else 'manifest lr_sonar'})", "bw deg": c["beamwidth_deg"], "depth m": c["depth_m"],
                     "footprint m": c["beam_footprint_m"], "posting m": c["posting_m"], "wall s": r["wall_s"]})
    sp = pd.DataFrame(rows); md(sp, "spacings_k", f"compare_{a.run_tag}.json")
    numbers.update({"n_pairs": cmp["n_pairs"], "n_hr_identical": cmp["n_hr_identical"], "n_lr_identical": cmp["n_lr_identical"], "n_k_identical": cmp["n_k_identical"],
                    "n_status_identical": cmp["n_status_identical"], "mismatches": cmp["mismatches"], "n_mismatches": len(cmp["mismatches"])})
    acq = [r for r in cmp["pairs"] if (P.R02 / "grid" / f"{r['pair_id'].split('__MGDS_')[0]}.json").exists()]
    numbers["acq_r02_pairs"] = {"n": len(acq), "n_lr_identical": sum(r["spacings"][1]["identical"] for r in acq), "n_k_identical": sum(r["k"]["identical"] for r in acq),
                                "n_hr_identical": sum(r["spacings"][0]["identical"] for r in acq), "mismatches": [r["pair_id"] for r in acq if r["mismatch_k_or_lr_native"]]}
    june = [r for r in cmp["pairs"] if r not in acq]
    numbers["june_pairs"] = {"n": len(june), "ids": [r["pair_id"] for r in june], "n_lr_identical": sum(r["spacings"][1]["identical"] for r in june), "n_k_identical": sum(r["k"]["identical"] for r in june),
                             "n_hr_identical": sum(r["spacings"][0]["identical"] for r in june)}
    # per-k verdicts of the mismatching pairs (verdicts, not a curve)
    rows = []
    for r in cmp["pairs"]:
        if r["mismatch_k_or_lr_native"]:
            rows.append({"pair_id": r["pair_id"], "lr_native computed": r["spacings"][1]["computed"], "lr_native manifest": r["spacings"][1]["manifest"], "k computed": r["k"]["computed"], "k manifest": r["k"]["manifest"],
                         "per-k verdicts (this run)": "; ".join(f"{k}: {v}" for k, v in (r["k"].get("per_k") or {}).items()), "depth basis": r["c2a"]["depth_basis"], "sonar source": r["c2a"]["sonar_source"]})
    md(pd.DataFrame(rows) if rows else pd.DataFrame([{"pair_id": "none", "note": "no mismatch"}]), "mismatches", f"compare_{a.run_tag}.json")
    # products
    rows = []
    for r in cmp["pairs"]:
        p = r["products"]
        if not p.get("built"):
            rows.append({"pair_id": r["pair_id"], "built": False, "note": p.get("note"), "existing on OAK": p.get("existing_products_on_oak")}); continue
        f = p["files"]
        rows.append({"pair_id": r["pair_id"], "built": True, "note": "", "existing on OAK": True, "rasters NaN identical (7)": p["all_rasters_nan_identical"], "max |diff| over rasters": f"{p['max_abs_diff_over_rasters']:.3g}",
                     "rasters within 1e-6": p["all_rasters_within_1e-6"], "bit identical": p["all_rasters_bit_identical"], "QA numbers within 1e-6": p["qa_all_within_1e-6"],
                     "flags existing / rehearsal": f"{p['flags_existing']} / {p['flags_rehearsal']}", "flags identical": p["flags_identical"],
                     "files existing / read": f"{f['n_existing']} / {f['n_rehearsal']}", "files same": f["same"], "lost": ", ".join(f["lost"]) or "none", "added": ", ".join(f["added"]) or "none",
                     "all read rc 0": f["n_read_rc0"] == f["n_listed"], "format": p["mb_format"]["rehearsal"], "beam angle": p["beam_angle_method"]["rehearsal"], "products wall s": p["wall_s_products"]})
    md(pd.DataFrame(rows), "products", f"compare_{a.run_tag}.json")
    numbers["products"] = {k: cmp[k] for k in ("n_products_built", "n_products_rasters_within_1e-6", "n_products_bit_identical", "n_products_qa_within_1e-6", "n_products_flags_identical", "n_products_files_same", "products_not_matching")}
    # QA numbers per pair
    rows = []
    for r in cmp["pairs"]:
        p = r["products"]
        if p.get("built"):
            for k, v in p["qa"].items():
                rows.append({"pair_id": r["pair_id"], "qa key": k, "existing": v["existing"], "rehearsal": v["rehearsal"], "within 1e-6": v["within_1e-6"]})
    md(pd.DataFrame(rows), "products_qa", f"compare_{a.run_tag}.json")
    # supplement rows
    rows = []
    for r in cmp["pairs"]:
        rw = r["row"]
        rows.append({"pair_id": r["pair_id"], "columns": rw["n_columns"], "identical": rw["n_identical"], "differing": ", ".join(c["column"] for c in rw["differing"]) or "none",
                     "filled (were empty)": ", ".join(rw.get("filled_columns") or []) or "none", "usable computed / manifest": f"{r['usable']['computed']} / {r['usable']['manifest']}"})
    md(pd.DataFrame(rows), "rows", f"compare_{a.run_tag}.json")
    rows = []
    for r in cmp["pairs"]:
        for c in r["row"]["differing"]:
            rows.append({"pair_id": r["pair_id"], "column": c["column"], "manifest v2.1": c["manifest"], "supplement": str(c["supplement"])[:120]})
    md(pd.DataFrame(rows) if rows else pd.DataFrame([{"pair_id": "none"}]), "rows_differing", f"compare_{a.run_tag}.json")
    numbers["rows"] = {"n_columns": cmp["pairs"][0]["row"]["n_columns"], "n_usable_identical": cmp["n_usable_identical"],
                       "differing_columns_union": sorted({c["column"] for r in cmp["pairs"] for c in r["row"]["differing"]})}
    # C1
    md(pd.DataFrame([{"rows": c1["n_rows"], "agree": c1["n_agree"], "disagree": c1["n_disagree"], "recorded null": c1["n_recorded_null"]}]), "c1_summary", "c1_check.json")
    md(pd.DataFrame(c1["rows"])[["pair_id", "available", "flags", "rule_C1", "recorded", "recorded_reason", "ruling_source", "agree"]], "c1_rows", "c1_check.json")
    numbers["c1"] = {k: c1[k] for k in ("n_rows", "n_agree", "n_disagree", "n_recorded_null")}
    # sealed records
    rows = []
    for s in sr["sealed_pairs"]:
        m = s["manifest"]; h = s.get("harmonize_record") or {}; g = s.get("grid_record") or {}; ci = s["c2a_inputs_the_step_will_use"]
        rows.append({"pair_id": s["pair_id"], "set": s["set"], "unit": s["unit"], "harmonized files recorded": yn(bool(m.get("harmonized_path"))) + f" ({m.get('harmonized_path')})",
                     "hr_native (manifest)": m.get("hr_native_res_m"), "hr_res (harmonize record)": h.get("hr_res_m"), "lr_native (manifest)": m.get("lr_native_res_m"),
                     "k (manifest)": m.get("max_recoverable_k"), "k (June record)": (s.get("june_c2c_sweep") or {}).get("max_recoverable_k"),
                     "coreg (record)": (f"{h['coreg'].get('offset_m')} m, pass {h['coreg'].get('pass')}" if h.get("coreg") else m.get("coreg_status")), "qa_status (manifest)": m.get("qa_status"),
                     "ship_products_usable (manifest)": m.get("ship_products_usable"), "sonar string -> bw": f"{ci['sonar']!r} -> {ci['beamwidth_deg']} deg ({ci['beamwidth_key']}; {'grid record' if ci['sonar_source'].startswith('ACQ-R02 grid record') else 'manifest lr_sonar'})",
                     "format (grid record)": g.get("format"), "k rule at the sealed step": s["k_rule_at_the_sealed_step"], "raw swath dir on OAK": s["raw_swath_dir_present_in_oak_listing"]})
    md(pd.DataFrame(rows), "sealed_records", "sealed_records.json")
    rows = [{"cruise": c, "plan exists": v["plan_exists"], "swath files": v["n_swath_files"], "advertised GB": v["swath_advertised_gb"], "nav files": v["n_nav_files"], "NCEI sonar subdir": ", ".join(v["ncei_sonar_subdirs"]),
             "June fetch mode": (v.get("fetch_list_row") or {}).get("fetch_mode"), "June whole_GB": (v.get("fetch_list_row") or {}).get("whole_GB"), "on OAK raw_lr_swath": v["on_oak_raw_lr_swath_listing"]} for c, v in sr["lockbox_fetch_plan"].items()]
    md(pd.DataFrame(rows), "lockbox_fetch_plan", "sealed_records.json (from stage_b_file_plan_2026-06-22.csv)")
    rows = [{"cruise": c, "MB-System format": v["mb_format"], "sonar string": v["sonar"], "bw deg (key)": f"{v['beamwidth_deg']} ({v['beamwidth_key']})", "files": v["n_files"],
             "builder run on this format: development pairs": ", ".join(v["builder_run_on_format_development"]) or "none",
             "ACQ-R04 corpus cruises / blocks with products": (f"{v['builder_run_on_format_acq_r04_corpus']['n_cruises']} / {v['builder_run_on_format_acq_r04_corpus']['n_blocks_products_available']}" if v["builder_run_on_format_acq_r04_corpus"] else "none"),
             "ever run": v["ever_run"]} for c, v in sr["builder_formats"]["confirmatory"].items()]
    md(pd.DataFrame(rows), "formats", "sealed_records.json")
    numbers["sealed"] = {"lockbox_plan": {c: {"n_swath_files": v["n_swath_files"], "gb": v["swath_advertised_gb"], "on_oak": v["on_oak_raw_lr_swath_listing"]} for c, v in sr["lockbox_fetch_plan"].items()},
                         "formats": {c: {"fmt": v["mb_format"], "ever_run": v["ever_run"], "corpus_blocks": (v["builder_run_on_format_acq_r04_corpus"] or {}).get("n_blocks_products_available")} for c, v in sr["builder_formats"]["confirmatory"].items()},
                         "lockbox_k_manifest": {s["pair_id"]: s["manifest"]["max_recoverable_k"] for s in sr["sealed_pairs"] if s["set"] == "lockbox"},
                         "lockbox_k_june": {s["pair_id"]: (s.get("june_c2c_sweep") or {}).get("max_recoverable_k") for s in sr["sealed_pairs"] if s["set"] == "lockbox"},
                         "lockbox_bw_default": {s["pair_id"]: s["c2a_inputs_the_step_will_use"]["beamwidth_deg"] for s in sr["sealed_pairs"] if s["set"] == "lockbox"}}
    # ledger
    md(pd.DataFrame(run["ledger"]), "ledger", f"step1_run_rehearsal_{a.run_tag}.json")
    numbers["ledger"] = {"n": len(run["ledger"]), "n_not_built": sum(1 for l in run["ledger"] if l["status"] in ("not built", "unavailable")), "n_failed": sum(1 for l in run["ledger"] if "fail" in str(l["status"]))}
    # timing
    md(pd.DataFrame([{"pair_id": r["pair_id"], "wall s (whole pair)": r["wall_s"], "products wall s": r["products"].get("wall_s_products"), "host": r["host"], "cpu": r["cpu_model"]} for r in cmp["pairs"]]), "timing", f"compare_{a.run_tag}.json")
    # freeze
    if fz:
        md(pd.DataFrame([{"file": k, "sha256": v} for k, v in fz["files"].items()]), "freeze_files", Path(fz["run_record"]).name)
        numbers["freeze"] = {"status": fz["status"], "n_files": fz["n_files"], "sealed_step1_sha256": fz["files"]["src/phase4/sealed_step1.py"], "commit": fz["commit"], "mbsystem": fz["mbsystem"],
                             "container_digest": fz["container"]["digest"], "sandbox_tar_sha256": fz["container"]["sandbox_tar_sha256"],
                             "record_file": ("freeze_record.json" if fz_p.exists() else "freeze_record_candidate.json"), "record_sha256": P.sha256_file(fz_p if fz_p.exists() else fz_c)}
    numbers["supplement"] = {"path": run["supplement"], "sha256": run["supplement_sha256"], "n_rows": run["n_rows"]}
    pv = P.REPORT_DIR / "preserve_verify.json"
    if pv.exists():
        numbers["preserve"] = {k: v for k, v in json.loads(pv.read_text()).items() if k in ("destination", "n_files", "n_bad", "bytes", "sha256sums_sha256")}
    P.write_json(P.REPORT_DIR / "tables.json", numbers, mode=0o644)
    print(json.dumps({k: v for k, v in numbers.items() if k not in ("fixed_inputs",)}, indent=1, default=str)[:4000])
    return 0


if __name__ == "__main__":
    sys.exit(main())
